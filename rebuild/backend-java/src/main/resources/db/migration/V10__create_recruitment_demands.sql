create table if not exists recruitment_demands (
    id bigint generated by default as identity primary key,
    job_id bigint,
    owner_hr_id bigint not null,
    request_no varchar(64) not null,
    requester_name varchar(100) not null,
    department varchar(100) not null,
    hiring_manager_name varchar(100) not null,
    requested_at timestamp with time zone not null default current_timestamp,
    accepted_at timestamp with time zone,
    target_date date,
    priority varchar(20) not null default 'medium',
    headcount integer not null default 1,
    status varchar(20) not null default 'open',
    close_reason varchar(500),
    downgrade_reason varchar(500),
    note varchar(2000),
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp
);

create index if not exists idx_recruitment_demands_owner on recruitment_demands (owner_hr_id);
create index if not exists idx_recruitment_demands_status on recruitment_demands (status);
create index if not exists idx_recruitment_demands_job on recruitment_demands (job_id);
