create table if not exists agent_call_logs (
    id bigint generated by default as identity primary key,
    conversation_id bigint,
    user_id bigint,
    action varchar(100) not null,
    tool_name varchar(100),
    input_json jsonb,
    output_json jsonb,
    status varchar(20) not null default 'success',
    duration_ms bigint,
    created_at timestamp with time zone not null default current_timestamp
);

create index if not exists idx_agent_call_logs_conversation on agent_call_logs (conversation_id);
create index if not exists idx_agent_call_logs_user on agent_call_logs (user_id);
create index if not exists idx_agent_call_logs_action on agent_call_logs (action);
