create table if not exists talent_maps (
    id bigint generated by default as identity primary key,
    name varchar(200) not null,
    job_id bigint,
    department varchar(120) not null default '',
    owner_hr_id bigint,
    board_json text,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp
);

create table if not exists talent_map_companies (
    id bigint generated by default as identity primary key,
    map_id bigint not null,
    company_name varchar(200) not null,
    city varchar(80) not null default '',
    region varchar(80) not null default '',
    industry varchar(120) not null default '',
    priority varchar(40) not null default 'medium',
    note text,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp
);

create table if not exists talent_map_people (
    id bigint generated by default as identity primary key,
    map_id bigint not null,
    company_id bigint,
    name varchar(120) not null,
    title varchar(160) not null default '',
    city varchar(80) not null default '',
    tags text,
    salary_range varchar(120) not null default '',
    contact_status varchar(80) not null default '未接触',
    evaluation varchar(120) not null default '',
    source varchar(160) not null default '',
    next_follow_at date,
    note text,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp
);

create index if not exists idx_talent_maps_owner on talent_maps (owner_hr_id);
create index if not exists idx_talent_map_companies_map on talent_map_companies (map_id);
create index if not exists idx_talent_map_people_map on talent_map_people (map_id);
create index if not exists idx_talent_map_people_company on talent_map_people (company_id);
create index if not exists idx_talent_map_people_status on talent_map_people (contact_status);
