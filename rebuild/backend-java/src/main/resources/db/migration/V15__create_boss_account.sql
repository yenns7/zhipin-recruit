-- BossAccount: BOSS直聘账号绑定，encrypted_cookie 使用 AES-GCM 加密存储
create table if not exists boss_account (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    boss_uid varchar(100),
    encrypted_cookie text,
    nickname varchar(100),
    avatar varchar(500),
    status varchar(20) not null default 'active',
    is_active boolean not null default false,
    cookie_count integer not null default 0,
    last_verified_at timestamp with time zone,
    last_verified_ok boolean,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp
);

create index if not exists idx_boss_account_user_id on boss_account (user_id);
create index if not exists idx_boss_account_user_active on boss_account (user_id, is_active);
