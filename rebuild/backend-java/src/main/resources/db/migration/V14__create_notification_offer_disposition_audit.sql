-- Notification: persisted notifications (read/unread model)
create table if not exists notification (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    title varchar(255) not null,
    message text,
    type varchar(50) not null default 'system',
    is_read boolean not null default false,
    created_at timestamp with time zone not null default current_timestamp
);

create index if not exists idx_notification_user_id on notification (user_id);
create index if not exists idx_notification_user_created on notification (user_id, created_at desc);

-- OfferRecord: persisted offer records replacing in-memory ConcurrentHashMap
create table if not exists offer_record (
    id bigint generated by default as identity primary key,
    candidate_id bigint not null,
    job_id bigint not null,
    salary varchar(255),
    start_date date,
    status varchar(20) not null default 'PENDING',
    remark varchar(2000),
    created_at timestamp with time zone not null default current_timestamp
);

create index if not exists idx_offer_record_candidate on offer_record (candidate_id);
create index if not exists idx_offer_record_job on offer_record (job_id);

-- CandidateDisposition: record when a candidate is rejected
create table if not exists candidate_disposition (
    id bigint generated by default as identity primary key,
    candidate_id bigint not null,
    reason varchar(1000),
    into_pool boolean not null default false,
    next_contact_at date,
    created_at timestamp with time zone not null default current_timestamp
);

create index if not exists idx_candidate_disposition_candidate on candidate_disposition (candidate_id);

-- AuditLog: persisted audit log replacing in-memory ArrayList
create table if not exists audit_log (
    id bigint generated by default as identity primary key,
    actor_id bigint,
    actor_name varchar(255),
    target_type varchar(100),
    target_id varchar(255),
    action varchar(255) not null,
    detail text,
    created_at timestamp with time zone not null default current_timestamp
);

create index if not exists idx_audit_log_actor on audit_log (actor_id, created_at desc);
create index if not exists idx_audit_log_target on audit_log (target_type, target_id);
