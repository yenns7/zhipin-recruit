-- UploadBatch: track resume upload batches
create table if not exists upload_batch (
    id bigint generated by default as identity primary key,
    owner_hr_id bigint not null,
    source varchar(50) not null default 'manual',
    channel varchar(50),
    notes varchar(1000),
    file_count integer not null default 0,
    created_at timestamp with time zone not null default current_timestamp
);

create index if not exists idx_upload_batch_owner on upload_batch (owner_hr_id);

-- CandidateTag: skill tags extracted from resumes
create table if not exists candidate_tag (
    id bigint generated by default as identity primary key,
    candidate_id bigint not null,
    tag varchar(100) not null,
    score integer not null default 0,
    created_at timestamp with time zone not null default current_timestamp
);

create index if not exists idx_candidate_tag_candidate on candidate_tag (candidate_id);
create index if not exists idx_candidate_tag_tag on candidate_tag (tag);

-- Add parse_status to candidates
alter table candidates add column if not exists parse_status varchar(20) not null default 'pending';
alter table candidates add column if not exists batch_id bigint;
alter table candidates add column if not exists parse_error varchar(2000);
